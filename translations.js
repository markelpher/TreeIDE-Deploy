let currentLang = localStorage.getItem('language') || (navigator.language.startsWith('pt') ? 'pt' : 'en');

function t(key) {
    return translations[currentLang][key] || key;
}

function setLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('language', lang);
    updateUI();
}

function getCurrentLang() {
    return currentLang;
}

function updateUI() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        if (el.id === 'fileName') return;
        const key = el.getAttribute('data-i18n');
        el.textContent = t(key);
    });

    // Update placeholders
    const editor = document.getElementById('editor');
    if (editor) {
        editor.placeholder = currentLang === 'pt'
            ? "raiz/\n    pasta/\n        arquivo.js\n        estilo.css\n    Readme.md"
            : "root/\n    folder/\n        file.js\n        style.css\n    Readme.md";
    }

    // Refresh icons because we might have replaced text icons or Lucide elements
    if (window.lucide) {
        window.lucide.createIcons();
    }
}

// Export for use in renderer.js
window.i18n = { t, setLanguage, updateUI, getCurrentLang };
